/**
 * 写入示例书。返回新书 id。
 *
 * 只写创意与设定：总纲/卷纲/单元要由作者自己生成，否则示例书会和真实
 * 流程的中间状态混在一起，作者接手时反而分不清哪些是自己产的。
 */
export async function seedSampleBook(): Promise<string> {
  const suffix = Date.now().toString(36).slice(-5)
  const created = await api.post<BookSnapshot>('/api/books', {
    bookId: `sample-fog-harbor-${suffix}`,
    title: SAMPLE.title,
    genre: SAMPLE.genre,
    idea: SAMPLE.idea,
  })
  const id = created.summary.id
  // 只写创意与设定：这些路径不参与大纲的结构化校验，所以不需要逐次追 revision。
  for (const [path, content] of Object.entries(SAMPLE.files)) {
    await api.put(`/api/books/${id}/file`, { path, content, baseRevision: created.revision })
  }
  return id
}
