#!/usr/bin/env bash
# Install the native SwiftUI app onto a connected physical iPhone.
#
# `pack_mobile.sh ios` produces a *distribution* artifact (IPA, or an unsigned
# simulator build). Debugging needs the opposite: build, sign, install and
# launch right now. Doing that by hand hides three traps this script closes.
#
#   1. The gomobile core (`out/mobile/DanmoNovel.xcframework`) is a binary
#      artifact that Swift source changes never refresh. Installing with a stale
#      xcframework silently ships an old Go core — the app runs, but the fix you
#      just made on the Go side is not in it. The core is rebuilt by default;
#      pass SKIP_CORE=1 to reuse it deliberately.
#   2. Device builds must be signed, and `DanmoNovel.xcodeproj` is generated by
#      xcodegen and gitignored, so the team can only be written into the
#      generator input.
#   3. `devicectl` lists simulators next to real hardware and has no "physical
#      only" switch; selecting without filtering by `hardware.reality` would
#      happily target a simulator UDID.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
BUNDLE_ID="${BUNDLE_ID:-com.danmo.novel}"
CONFIGURATION="${CONFIGURATION:-Debug}"
DEVICE="${DEVICE:-}"
DERIVED_DIR="$ROOT_DIR/out/ios-device"
VERSION="${RELEASE_VERSION#v}"
VERSION="${VERSION:-0.1.0}"

cd "$ROOT_DIR"

usage() {
  cat <<'EOF'
用法: ./scripts/install_ios.sh [--device <名称或 UDID>]

环境变量:
  DEVICE=<名称或 UDID>   选择目标设备（连接了多台真机时必填）
  APPLE_TEAM_ID=<TeamID>  签名团队；缺省时从钥匙串的 Apple Development 证书推导
  CONFIGURATION=Release   构建配置（默认 Debug，改完代码即可重装）
  BUNDLE_ID=...          默认 com.danmo.novel
  SKIP_CORE=1            跳过 gomobile 内核重建（默认重建，避免装到旧内核）
  NO_LAUNCH=1            只安装，不自动启动
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --device)
      DEVICE="${2:-}"
      [[ -n "$DEVICE" ]] || { echo 'ERROR: --device 需要一个名称或 UDID' >&2; exit 2; }
      shift 2
      ;;
    *)
      echo "ERROR: 未知参数 $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

# Resolve the target through devicectl's JSON: it is the only stable surface
# (the table output is column-aligned text and its Identifier column switches
# between UDID, ECID and CoreDevice ID depending on what the device exposes).
# Prints "<udid>\t<name>" and exits non-zero with an explanation on failure.
resolve_device() {
  python3 - "$1" <<'PY'
import json
import os
import subprocess
import sys
import tempfile

want = sys.argv[1]

fd, path = tempfile.mkstemp(suffix=".json")
os.close(fd)
try:
    proc = subprocess.run(
        ["xcrun", "devicectl", "list", "devices", "--json-output", path],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write("ERROR: 无法枚举设备（devicectl 失败）：\n" + proc.stderr)
        sys.exit(3)
    with open(path) as handle:
        payload = json.load(handle)
finally:
    os.unlink(path)

candidates = []
for device in payload.get("result", {}).get("devices", []):
    props = device.get("properties", {})
    hardware = props.get("hardware", {})
    state = props.get("state", {})
    connection = props.get("connection", {})
    if hardware.get("reality") != "physical":
        continue
    udid = hardware.get("udid") or device.get("identifier", "")
    name = state.get("name", "")
    candidates.append((udid, device.get("identifier", ""), name,
                       state.get("bootState", ""),
                       connection.get("state", "")))

if not candidates:
    sys.stderr.write(
        "ERROR: 没有检测到已连接的 iPhone。\n"
        "      用数据线连接（或在同一网络的「设备配对」里添加），解锁后重试。\n"
    )
    sys.exit(3)

def matched(entry):
    if want in entry:
        return True
    return want.lower() in entry[2].lower()

if want:
    hits = [entry for entry in candidates if matched(entry)]
    if len(hits) == 1:
        udid, _, name, boot, conn = hits[0]
        if conn != "connected" or boot != "booted":
            sys.stderr.write(
                f"ERROR: 「{name}」当前不可用（{conn or '未知状态'}）。\n"
                "      解锁设备、保持同一网络或重新插线后重试。\n"
            )
            sys.exit(3)
        print(f"{udid}\t{name}")
        sys.exit(0)
    if len(hits) > 1:
        sys.stderr.write(f"ERROR: 「{want}」匹配到多台设备：\n")
        for entry in hits:
            sys.stderr.write(f"  {entry[2]}  {entry[0]}\n")
        sys.exit(4)
    sys.stderr.write(f"ERROR: 找不到设备「{want}」。已配对/连接的 iPhone：\n")
    for entry in candidates:
        sys.stderr.write(f"  {entry[2]}  {entry[0]}  （{entry[4]}）\n")
    sys.exit(4)

# A paired device that is asleep, out of range or on another machine still shows
# up in the list with state "unavailable". Treating it as a target would fail
# later inside devicectl with a message about the device rather than the target.
ready = [entry for entry in candidates if entry[4] == "connected" and entry[3] == "booted"]
if not ready:
    sys.stderr.write("ERROR: 没有处于连接状态的真机，请解锁并保持连接：\n")
    for entry in candidates:
        sys.stderr.write(f"  {entry[2]}  {entry[0]}  （{entry[4] or '未知状态'}）\n")
    sys.exit(3)
if len(ready) > 1:
    sys.stderr.write("ERROR: 连接了多台真机，请用 DEVICE=<名称或 UDID> 指定：\n")
    for entry in ready:
        sys.stderr.write(f"  {entry[2]}  {entry[0]}\n")
    sys.exit(4)

print(f"{ready[0][0]}\t{ready[0][2]}")
PY
}

# An Apple Development certificate carries the team in its OU field, so the team
# does not have to be exported for every debug install.
detect_team() {
  python3 - <<'PY'
import re
import subprocess
import sys

listing = subprocess.run(
    ["security", "find-identity", "-v", "-p", "codesigning"],
    capture_output=True, text=True,
).stdout
for name in re.findall(r'"(Apple Development: [^"]+)"', listing):
    pem = subprocess.run(
        ["security", "find-certificate", "-c", name, "-p"],
        capture_output=True, text=True,
    ).stdout
    subject = subprocess.run(
        ["openssl", "x509", "-noout", "-subject"],
        input=pem, capture_output=True, text=True,
    ).stdout
    match = re.search(r"OU=([A-Z0-9]+)", subject)
    if match:
        print(match.group(1))
        sys.exit(0)
sys.exit(1)
PY
}

if ! command -v xcodegen >/dev/null; then
  echo 'ERROR: 需要 xcodegen（brew install xcodegen）' >&2
  exit 1
fi

echo "==> 选择真机"
if ! resolved="$(resolve_device "$DEVICE")"; then
  exit 1
fi
UDID="${resolved%%$'\t'*}"
DEVICE_NAME="${resolved#*$'\t'}"
echo "    $DEVICE_NAME · $UDID"

if [[ -z "${APPLE_TEAM_ID:-}" ]]; then
  APPLE_TEAM_ID="$(detect_team || true)"
fi
if [[ -z "${APPLE_TEAM_ID:-}" ]]; then
  echo 'ERROR: 没有可用的签名团队。请在 Xcode 登录 Apple ID，或 export APPLE_TEAM_ID=<TeamID>。' >&2
  exit 1
fi
echo "==> 签名团队 $APPLE_TEAM_ID · $CONFIGURATION"

if [[ "${SKIP_CORE:-0}" != "1" ]]; then
  echo "==> 重建 gomobile 内核"
  # gomobile bind is verbose even on success; keep the log for the failure case
  # instead of drowning the install summary in generated framework headers.
  CORE_LOG="$(mktemp -t danmo-core)"
  if ! ./scripts/build_go_mobile.sh ios >"$CORE_LOG" 2>&1; then
    echo 'ERROR: gomobile 内核构建失败：' >&2
    tail -n 30 "$CORE_LOG" >&2
    rm -f "$CORE_LOG"
    exit 1
  fi
  rm -f "$CORE_LOG"
else
  echo "==> 跳过 gomobile 内核重建（SKIP_CORE=1）"
fi

echo "==> 生成 Xcode 工程"
(
  cd native-ios
  RELEASE_VERSION="$VERSION" APPLE_TEAM_ID="$APPLE_TEAM_ID" xcodegen generate >/dev/null
)

echo "==> 构建 $VERSION ($CONFIGURATION)"
BUILD_LOG="$(mktemp -t danmo-build)"
if ! (
  cd native-ios
  xcodebuild -project DanmoNovel.xcodeproj -scheme DanmoNovel \
    -configuration "$CONFIGURATION" -destination "id=$UDID" \
    -derivedDataPath "$DERIVED_DIR" -allowProvisioningUpdates build
) >"$BUILD_LOG" 2>&1; then
  echo 'ERROR: 构建或签名失败：' >&2
  grep -E "error:|CODE_SIGN|Provisioning" "$BUILD_LOG" | tail -n 20 >&2
  rm -f "$BUILD_LOG"
  exit 1
fi
rm -f "$BUILD_LOG"

APP_PATH="$DERIVED_DIR/Build/Products/$CONFIGURATION-iphoneos/DanmoNovel.app"
[[ -d "$APP_PATH" ]] || { echo "ERROR: 构建产物不存在：$APP_PATH" >&2; exit 1; }

echo "==> 安装到 $DEVICE_NAME"
if ! xcrun devicectl device install app --device "$UDID" "$APP_PATH" >/dev/null; then
  echo 'ERROR: 安装失败。常见原因：设备锁屏、开发者模式未开启，或这台设备不在描述文件里。' >&2
  echo '       解锁后重试；首次连接需要在「设置 → 隐私与安全性 → 开发者模式」开启并重启。' >&2
  exit 1
fi

if [[ "${NO_LAUNCH:-0}" != "1" ]]; then
  echo "==> 启动 $BUNDLE_ID"
  LAUNCH_LOG="$(mktemp -t danmo-launch)"
  if ! xcrun devicectl device process launch --device "$UDID" --terminate-existing "$BUNDLE_ID" >"$LAUNCH_LOG" 2>&1; then
    # A locked phone refuses to foreground any app over SBMainWorkspace. The
    # install itself succeeded, so failing the whole target here would report
    # the wrong thing; say what to do and leave the app installed.
    if grep -q "unlocked" "$LAUNCH_LOG"; then
      echo "    $DEVICE_NAME 处于锁屏状态，未能自动启动。" >&2
      echo "    解锁后手动打开，或重新执行 make install-ios（SKIP_CORE=1 可跳过内核重建）。" >&2
      rm -f "$LAUNCH_LOG"
      echo "完成：$DEVICE_NAME 已安装 $BUNDLE_ID ${VERSION}（未启动）"
      exit 0
    fi
    echo 'ERROR: 启动失败：' >&2
    tail -n 15 "$LAUNCH_LOG" >&2
    rm -f "$LAUNCH_LOG"
    exit 1
  fi
  rm -f "$LAUNCH_LOG"
fi

echo "完成：$DEVICE_NAME 已安装 $BUNDLE_ID $VERSION"
